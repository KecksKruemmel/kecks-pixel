UMLAUTS = {"Ä": "A", "Ö": "O", "Ü": "U", "ä": "a", "ö": "o", "ü": "u"}


def all_glyphs():
    glyphs = {}
    for table in (UPPER, LOWER, DIGITS, PUNCT):
        glyphs.update({ch: (rows, 0) for ch, rows in table.items()})
    for ch, base in UMLAUTS.items():
        rows = list(glyphs[base][0])
        w = len(rows[0])
        dots = "".join("#" if i in (1, w - 2) else "." for i in range(w))
        if base.isupper():
            glyphs[ch] = ([dots, "." * w] + rows, -2)
        else:
            rows[0] = dots
            glyphs[ch] = (rows, 0)
    return glyphs
